/**
 * Standardized Multi-Tier validation loop for Python projects
 */
export async function validate(sandboxPath, packageManager, originalManifestContent, upgradeGroups, options) {
  const venv = getVenvBinaries(sandboxPath);

  // 1. Initialize isolated virtual environment in sandbox if not present
  if (!fs.existsSync(path.join(sandboxPath, '.venv'))) {
    const hostPython = getHostPythonCmd();
    console.log(`🐍 Initializing isolated Python virtual environment (.venv) via ${hostPython}...`);
    try {
      execSync(`${hostPython} -m venv .venv`, { cwd: sandboxPath, stdio: 'pipe' });
    } catch (err) {
      return { 
        passed: false, 
        tier: 'A (Virtual Environment Initialization)', 
        error: `Failed to create virtual environment: ${err.message}` 
      };
    }
  }

  // 2. Write candidate requirements.txt into the sandbox
  const reqPath = path.join(sandboxPath, 'requirements.txt');
  const upgradesToApply = upgradeGroups.flatMap(group => group.packages);
  const activeContent = upgradesToApply.length > 0 
    ? updateRequirementsContent(originalManifestContent, upgradesToApply)
    : originalManifestContent;

  fs.writeFileSync(reqPath, activeContent, 'utf-8');

  // Tier A: Package Installation via sandbox pip
  console.log(`📦 Running Python package installation: pip install -r requirements.txt`);
  try {
    execSync(`"${venv.pip}" install -r requirements.txt`, { cwd: sandboxPath, stdio: 'pipe', encoding: 'utf-8' });
  } catch (err) {
    const fullLog = [err.stdout, err.stderr, err.message].filter(Boolean).join('\n');
    return { passed: false, tier: 'A (Installation / pip)', error: fullLog };
  }

  // Tier B: Python Bytecode Compilation & Syntax Check
  console.log(`⚡ Running Python bytecode compilation check (python -m compileall)...`);
  try {
    execSync(`"${venv.python}" -m compileall -q .`, { cwd: sandboxPath, stdio: 'pipe', encoding: 'utf-8' });
  } catch (err) {
    const fullLog = [err.stdout, err.stderr, err.message].filter(Boolean).join('\n');
    return { passed: false, tier: 'B (Syntax / Bytecode Compilation)', error: fullLog };
  }

  // Tier C: CLI Module Import Check
  const entrypoint = findCliEntrypoint(sandboxPath);
  if (entrypoint) {
    const modName = path.parse(entrypoint).name;
    console.log(`⚡ Running CLI module import integrity check on ${entrypoint}...`);
    try {
      execSync(`"${venv.python}" -c "import ${modName}"`, { cwd: sandboxPath, stdio: 'pipe', encoding: 'utf-8' });
    } catch (err) {
      // If it's a CLI that requires args or exits normally with SystemExit, that is valid
      if (!String(err.stderr || '').includes('SystemExit: 0')) {
        const fullLog = [err.stdout, err.stderr, err.message].filter(Boolean).join('\n');
        return { passed: false, tier: 'C (CLI Module Import)', error: fullLog };
      }
    }

    // Tier E: CLI Boot Smoke Test (--help)
    console.log(`⚡ Launching CLI smoke test check ("${entrypoint} --help")...`);
    try {
      execSync(`"${venv.python}" "${entrypoint}" --help`, { cwd: sandboxPath, stdio: 'pipe', encoding: 'utf-8' });
    } catch (err) {
      const fullLog = [err.stdout, err.stderr, err.message].filter(Boolean).join('\n');
      return { passed: false, tier: 'E (CLI Boot Smoke Test)', error: fullLog };
    }
  }

  // Tier D: Test Suites / Autogenerated Module Crawler
  if (!options.skipTests) {
    let ranTests = false;

    // Check for project-native pytest
    try {
      execSync(`"${venv.python}" -m pytest --version`, { cwd: sandboxPath, stdio: 'ignore' });
      if (fs.existsSync(path.join(sandboxPath, 'tests')) || fs.existsSync(path.join(sandboxPath, 'test'))) {
        console.log(`⚡ Running project-native pytest test suite (Tier D)...`);
        execSync(`"${venv.python}" -m pytest`, { cwd: sandboxPath, stdio: 'pipe', encoding: 'utf-8' });
        ranTests = true;
      }
    } catch (err) {
      if (err.stdout || err.stderr) {
        return { passed: false, tier: 'D (Test Suites / pytest)', error: `${err.stdout || ''}\n${err.stderr || ''}` };
      }
    }

    // If no native tests ran, execute the autogenerated module import crawler
    if (!ranTests) {
      console.log('🤖 No local test suite found. Activating autogenerated Python module crawler (Tier D)...');
      const testFile = writeAutogeneratedPythonTest(sandboxPath);
      try {
        execSync(`"${venv.python}" "${testFile}"`, { cwd: sandboxPath, stdio: 'pipe', encoding: 'utf-8' });
        fs.unlinkSync(path.join(sandboxPath, testFile));
      } catch (err) {
        try { fs.unlinkSync(path.join(sandboxPath, testFile)); } catch {}
        const fullLog = [err.stdout, err.stderr, err.message].filter(Boolean).join('\n');
        return { passed: false, tier: 'D (Autogenerated Module Crawler)', error: fullLog };
      }
    }
  }

  return { passed: true };
}