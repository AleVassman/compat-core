/**
 * Queries PyPI for latest releases of declared packages
 */
export async function scanUpdates(targetDir) {
  const content = fs.readFileSync(path.join(targetDir, 'requirements.txt'), 'utf-8');
  const entries = parseRequirementsTxt(content).filter(e => e.isRequirement);

  console.log(`📡 Querying PyPI registry for ${entries.length} Python dependencies...`);

  const results = await Promise.all(entries.map(async (entry) => {
    const url = `https://pypi.org/pypi/${entry.name}/json`;
    const currentClean = cleanSemverRange(entry.declaredRange);

    try {
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), 8000);
      const res = await fetch(url, { signal: controller.signal });
      clearTimeout(timeout);

      if (!res.ok) {
        throw new Error(`PyPI returned HTTP ${res.status}`);
      }

      const data = await res.json();
      const latestVersion = data.info?.version;
      if (!latestVersion) throw new Error('No latest version found in PyPI metadata');

      const updateType = determineUpdateType(currentClean, latestVersion);

      return {
        name: entry.name,
        declaredRange: entry.declaredRange,
        currentClean,
        latestVersion,
        updateType,
        peerDependencies: {},
        error: null
      };
    } catch (err) {
      return {
        name: entry.name,
        declaredRange: entry.declaredRange,
        currentClean,
        latestVersion: null,
        updateType: 'none',
        peerDependencies: {},
        error: err.message
      };
    }
  }));

  return {
    upgrades: results.filter(item => item.updateType !== 'none' && !item.error),
    errors: results.filter(item => item.error)
  };
}

/**
 * Couples interdependent Python packages into Atomic Units
 */
export function solve(upgrades) {
  const atomicCoupledPairs = [
    ['pydantic', 'pydantic-core', 'pydantic-settings'],
    ['fastapi', 'starlette', 'uvicorn'],
    ['django', 'djangorestframework', 'django-cors-headers'],
    ['celery', 'kombu', 'billiard'],
    ['sqlalchemy', 'alembic'],
    ['pytest', 'pytest-asyncio', 'pytest-cov'],
    ['langchain', 'langchain-core', 'langchain-community'],
    ['click', 'rich'],
    ['requests', 'urllib3'],
    ['httpx', 'httpcore']
  ];

  const atomicGroups = [];
  const assigned = new Set();

  upgrades.forEach(pkg => {
    if (assigned.has(pkg.name.toLowerCase())) return;
    const matchedPair = atomicCoupledPairs.find(pair => 
      pair.some(p => p.toLowerCase() === pkg.name.toLowerCase())
    );

    if (matchedPair) {
      const group = [];
      matchedPair.forEach(name => {
        const found = upgrades.find(u => u.name.toLowerCase() === name.toLowerCase());
        if (found) {
          group.push(found);
          assigned.add(name.toLowerCase());
        }
      });
      if (group.length > 0) {
        atomicGroups.push({
          id: group.map(g => g.name).join('+'),
          packages: group,
          isAtomic: group.length > 1
        });
      }
    } else {
      atomicGroups.push({
        id: pkg.name,
        packages: [pkg],
        isAtomic: false
      });
      assigned.add(pkg.name.toLowerCase());
    }
  });

  return { conflicts: [], atomicGroups };
}

