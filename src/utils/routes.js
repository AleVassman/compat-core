import fs from 'fs';
import path from 'path';

const TEST_FILENAME = 'compat-autogenerated.test.js';

/**
 * Normalizes a file path into a clean, public Next.js URL route
 * Handles Route Groups (e.g. "(auth)/login" -> "/login") and index/page layouts
 */
function normalizeRoutePath(segments) {
  const cleanSegments = segments.filter(seg => {
    // 1. Skip Next.js parallel routes (e.g., @dashboard)
    if (seg.startsWith('@')) return false;
    // 2. Skip Next.js private folders (e.g., _components)
    if (seg.startsWith('_')) return false;
    // 3. Skip dynamic/parameterized folders (e.g., [id])
    if (seg.startsWith('[') && seg.endsWith(']')) return false;
    return true;
  }).map(seg => {
    // 4. Strip Route Groups parentheses (e.g. "(auth)" -> "")
    if (seg.startsWith('(') && seg.endsWith(')')) {
      return '';
    }
    return seg;
  }).filter(Boolean); // Filter out empty segments resulting from stripped parens

  const urlPath = '/' + cleanSegments.join('/');
  return urlPath === '' ? '/' : urlPath;
}

/**
 * Recursively scans Next.js app or pages directories for valid static page paths
 */
function scanDirectoryForPages(dir, baseDir, mode, routeList = new Set()) {
  if (!fs.existsSync(dir)) return routeList;

  let files;
  try {
    files = fs.readdirSync(dir);
  } catch {
    return routeList;
  }

  files.forEach(file => {
    const filePath = path.join(dir, file);
    let stat;
    try {
      stat = fs.statSync(filePath);
    } catch {
      return;
    }

    if (stat.isDirectory()) {
      scanDirectoryForPages(filePath, baseDir, mode, routeList);
    } else {
      const ext = path.extname(file);
      if (!['.js', '.jsx', '.ts', '.tsx'].includes(ext)) return;

      const relativePath = path.relative(baseDir, filePath);
      const parsedPath = path.parse(relativePath);
      const segments = parsedPath.dir ? parsedPath.dir.split(path.sep) : [];

      if (mode === 'app') {
        // App Router: Pages are defined by "page.tsx" or "page.jsx" files inside directories
        if (parsedPath.name === 'page') {
          routeList.add(normalizeRoutePath(segments));
        }
      } else {
        // Pages Router: Pages are defined by any TS/JS file name except _app, _document, _error, and api
        if (!['_app', '_document', '_error', 'api'].includes(parsedPath.name)) {
          if (parsedPath.name !== 'index') {
            segments.push(parsedPath.name);
          }
          routeList.add(normalizeRoutePath(segments));
        }
      }
    }
  });

  return routeList;
}

/**
 * Dynamically resolves all static pages inside the project
 * @param {string} targetDir 
 * @returns {Array<string>} List of unique public URL paths (e.g., ["/", "/about", "/timesheets"])
 */
export function discoverProjectRoutes(targetDir) {
  const routes = new Set();

  const directoriesToCheck = [
    { path: path.join(targetDir, 'src', 'app'), mode: 'app' },
    { path: path.join(targetDir, 'app'), mode: 'app' },
    { path: path.join(targetDir, 'src', 'pages'), mode: 'pages' },
    { path: path.join(targetDir, 'pages'), mode: 'pages' }
  ];

  directoriesToCheck.forEach(dir => {
    scanDirectoryForPages(dir.path, dir.path, dir.mode, routes);
  });

  // Always guarantee at least the homepage is present
  routes.add('/');

  return Array.from(routes);
}

/**
 * Generates a temporary native Node.js test runner file inside the sandbox
 * @param {string} sandboxPath 
 * @param {Array<string>} routes 
 */
export function writeAutogeneratedTestSuite(sandboxPath, routes) {
  const testSuitePath = path.join(sandboxPath, TEST_FILENAME);

  // Writes native ES6 ESM imports utilizing the native node:test runner
  let content = `import { test } from 'node:test';\n`;
  content += `import assert from 'node:assert';\n\n`;
  content += `const smokePort = process.env.PORT || '3000';\n\n`;

  content += `console.log('🤖 Autogenerated Test Suite: Ready to crawl ${routes.length} project routes.');\n\n`;

  routes.forEach(route => {
    content += `test('GET ${route}', async () => {\n`;
    content += `  const res = await fetch(\`http://localhost:\${smokePort}${route}\`);\n`;
    content += `  assert.ok(res.status < 500, \`Expected HTTP status < 500 on page rendering, received \${res.status}\`);\n`;
    content += `});\n\n`;
  });

  fs.writeFileSync(testSuitePath, content, 'utf-8');
  return TEST_FILENAME;
}

/**
 * Removes the temporary test runner file from the sandbox
 * @param {string} sandboxPath 
 */
export function cleanupAutogeneratedTestSuite(sandboxPath) {
  const testSuitePath = path.join(sandboxPath, TEST_FILENAME);
  if (fs.existsSync(testSuitePath)) {
    try {
      fs.unlinkSync(testSuitePath);
    } catch {
      // Fail-silent
    }
  }
}